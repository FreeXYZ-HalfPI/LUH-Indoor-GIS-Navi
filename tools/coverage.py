"""Write docs/COVERAGE.md: how many rooms each building has, how many the app
can route to, per floor, and why the others are not routable yet.

Reads data/indoor/<b>/rooms.json (tools/crawl_rooms.py) and
data/indoor/<b>/build_report.json (tools/build_indoor.py build). Run it after
crawling or rebuilding. Only the Python standard library is used.
"""
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "COVERAGE.md"

FIX = {   # what a contributor can do about each reason
    "no corridor reachable": "trace a corridor nearby in `source.json`",
    "floor not mapped": "register the floor (`build_indoor.py fit`) and trace its corridors",
    "outside the building outline": "check the OSM outline, or add the room to `force_rooms`",
    "no red highlight on its plan": "place it by hand with `room_points`",
    "not reachable from the entrances": "connect its corridor to stairs or the rest of the floor",
    "skipped by hand": "see `skip_rooms` in `source.json`",
}


def floor_name(code):
    lvl = -int(code[1:]) if code[0] in "U-" else int(code)
    return "ground" if lvl == 0 else f"+{lvl}" if lvl > 0 else str(lvl)


def main():
    rows, details, totals = [], [], Counter()
    names = {b["id"]: b["name"] for b in json.loads((ROOT / "web" / "data" / "buildings.json").read_text(encoding="utf-8"))}
    for f in sorted((ROOT / "data" / "indoor").glob("*/rooms.json")):
        crawl = json.loads(f.read_text(encoding="utf-8"))
        bid = crawl["building"]
        rep_file = f.parent / "build_report.json"
        rep = json.loads(rep_file.read_text(encoding="utf-8")) if rep_file.exists() else None
        unrouted = rep["unrouted"] if rep else {r["id"]: "no indoor graph yet" for r in crawl["rooms"]}
        total, listed = len(crawl["rooms"]), sum(r["listed"] for r in crawl["rooms"])
        routable = total - len(unrouted)
        totals.update(total=total, listed=listed, routable=routable)
        rows.append(f"| {bid} {names.get(bid, '')} | {listed} | {total} | **{routable}** | {routable / total:.0%} | {crawl['crawled']} |")

        per = defaultdict(lambda: [0, 0])
        for r in crawl["rooms"]:
            per[r["floor"]][0] += 1
            per[r["floor"]][1] += r["id"] not in unrouted
        lines = [f"### {bid} {names.get(bid, '')}", "",
                 "| floor | rooms | routable |", "|---|---:|---:|"]
        lines += [f"| {floor_name(c)} (`{c}`) | {n} | {ok} |" for c, (n, ok) in per.items()]
        by_reason = defaultdict(list)
        for rid, why in unrouted.items():
            by_reason[why].append(rid)
        if by_reason:
            lines += ["", "Not routable yet:", ""]
            for why, ids in sorted(by_reason.items(), key=lambda kv: -len(kv[1])):
                fix = f" → {FIX[why]}" if why in FIX else ""
                lines.append(f"<details><summary>{len(ids)} × {why}{fix}</summary>\n\n"
                             + " ".join(f"`{i}`" for i in sorted(ids)) + "\n</details>\n")
        details.append("\n".join(lines))

    md = ["# Room coverage", "",
          "Generated by `python3 tools/coverage.py` from the crawler output",
          "(`tools/crawl_rooms.py`) and the indoor builder (`tools/build_indoor.py`).",
          "**Public** rooms are the ones listed on LUH Rauminfo; **found** are all rooms",
          "the crawler discovered; **routable** ones have a door-to-door route in the app.", "",
          "| building | public | found | routable | share | crawled |", "|---|---:|---:|---:|---:|---|",
          *rows,
          f"| **total** | {totals['listed']} | {totals['total']} | **{totals['routable']}** | "
          f"{totals['routable'] / max(1, totals['total']):.0%} | |", "",
          "Want to help? Pick a reason below, fix it in the building's `source.json`,",
          "run `python3 tools/build_indoor.py build <building>` and this script, and open a pull request.", "",
          *details]
    OUT.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {totals['routable']}/{totals['total']} rooms routable")


if __name__ == "__main__":
    main()
